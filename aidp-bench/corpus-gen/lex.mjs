function fmtNum(n, thou, dec, noDecimals = false) {
  const neg = n < 0; const abs = Math.abs(n);
  const [int, fr] = (noDecimals ? String(Math.round(abs)) : abs.toFixed(2)).split('.');
  const grouped = int.replace(/\B(?=(\d{3})+(?!\d))/g, thou);
  return (neg ? '-' : '') + grouped + (fr != null ? dec + fr : '');
}
