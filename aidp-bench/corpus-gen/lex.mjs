// Rounded exactly as fmtNum rounds what is printed (half away from zero), so a negative amount in a
// locale without decimals holds the same digits in the key as on the page.
export const gtNum = (n, noDecimals = false) => (noDecimals ? String((n < 0 ? -1 : 1) * Math.round(Math.abs(n)) || 0) : n.toFixed(2));
